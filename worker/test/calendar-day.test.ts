import { expect, it } from "vitest";
import { validCalendarDay } from "../src/lib";

it.each(["0001-01-01", "0004-02-29", "0099-12-31", "0100-02-28", "1600-02-29",
  "1900-02-28", "2000-02-29", "2024-02-29", "2026-01-31", "2026-04-30", "2026-12-31",
  "2100-02-28", "2400-02-29", "9999-12-31"])("keeps supported calendar day %s unchanged", day => {
  expect(validCalendarDay(day)).toBe(day);
});

it.each(["0000-01-01", "0001-02-29", "0100-02-29", "1700-02-29", "1800-02-29", "1900-02-29",
  "2001-02-29", "2026-02-29", "2026-02-30", "2026-02-31", "2026-04-31", "2026-06-31",
  "2026-09-31", "2026-11-31", "2100-02-29", "2026-00-01", "2026-13-01", "2026-01-00",
  "2026-01-32", "10000-01-01", "-0001-01-01", "2026-1-01", "2026-01-1", "2026-01-01T00:00:00Z",
  " 2026-01-01", "2026-01-01\n", "", null, undefined, 20260101])("rejects unsupported calendar value %s", day => {
  expect(validCalendarDay(day)).toBeUndefined();
});
