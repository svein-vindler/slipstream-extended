def test_genuine_110_bulk_history_is_not_rebuilt_or_relabelled(monkeypatch):
    fixture = json.loads((Path(__file__).parent / "fixtures/coach_engine_110_transition.json").read_text())
    store = CountingStore()
    store.objects = {key: base64.b64decode(body) for key, body in fixture["objects_base64"].items()}
    store.objects["activities/2026/42/activity.tcx"] = TCX
    old = {key: body for key, body in store.objects.items() if "/canonical/" in key}
    assert {json.loads(gzip.decompress(body))["analyzer_version"] for body in old.values()} == {"1.1.0"}

    def must_not_rebuild(**kwargs):
        pytest.fail("Unchanged genuine 1.1.0 input must not be regenerated by engine upgrade")

    monkeypatch.setattr(coach_backfill, "build_coach_input", must_not_rebuild)
    result = coach_backfill.run(store=store, max_activities=1)
    assert result["generated_this_run"] == 0
    assert all(store.objects[key] == body for key, body in old.items())


def test_new_running_segments_encrypted_backup_preserves_exact_producer_bytes(tmp_path):
    fixture = build_case()
    objects = {}
    for key, encoded in fixture["objects_base64"].items():
        body = base64.b64decode(encoded)
        if "/canonical/" in key:
            objects[key] = body
        elif key.startswith("coach/profiles/"):
            profile = validate_profile({**json.loads(body), "created_at": "2026-01-01T00:00:00Z"})
            objects[f"coach/profiles/v1/{profile['effective_from']}/{profile['profile_id']}.json"] = backup._json_bytes(profile)
    analysis = json.loads(gzip.decompress(next(body for key, body in objects.items() if "/canonical/" in key)))
    assert analysis["analyzer_version"] == TRAINING_EFFECT_ANALYZER_VERSION
    assert analysis["stored_context_snapshot"]["reference_time_utc"] == "2026-10-07T23:30:00.000Z"
    assert analysis["recorded_running_metrics"]["kilometer_splits"]["items"][0]["average_power"]["value"] == 150
    target = tmp_path / "synthetic-segments.slbk"
    backup.create_backup(MemorySource(objects), Scope((("2026", "42"),)), target, PASSWORD)
    assert backup.verify_backup(target, PASSWORD).objects == objects


def current_analysis():
    fixture = build_case()
    key, encoded = next((key, value) for key, value in fixture["objects_base64"].items()
                        if "/canonical/" in key)
    return key, json.loads(gzip.decompress(base64.b64decode(encoded)))


def test_backup_format_accepts_complete_current_producer_without_mutating_it():
    key, analysis = current_analysis()
    original = copy.deepcopy(analysis)
    backup._validate_value(key, analysis)
    assert analysis == original


def test_backup_format_rejects_unbounded_integer_in_segment_coverage():
    key, analysis = current_analysis()
    analysis["recorded_running_metrics"]["kilometer_splits"]["items"][0]["average_power"]["coverage"]["valid_seconds"] = 10 ** 400
    with pytest.raises(backup.BackupError):
        backup._validate_value(key, analysis)


def test_backup_format_keeps_small_positive_contributions_when_display_time_rounds_to_zero():
    decoded = decoded_source()
    decoded["messages"]["record_mesgs"] = [
        {"timestamp": START.isoformat(), "distance": 999.99, "power": 100},
        {"timestamp": (START + timedelta(seconds=1)).isoformat(), "distance": 2000, "power": 100},
    ]
    analysis = analyze(decoded, endurance=normalize_endurance_session(DTO, synthetic_tcx()))
    cover = analysis["recorded_running_metrics"]["kilometer_splits"]["items"][0]["average_power"]["coverage"]
    assert cover == {"valid_seconds": 0, "eligible_seconds": 0, "excluded_gap_seconds": 0,
                     "contributing_intervals": 1, "status": "partial"}
    key = f"activities/2026/42/coach-input/v1/canonical/{analysis['analysis_id']}.json"
    backup._validate_value(key, analysis)
